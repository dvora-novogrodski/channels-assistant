// Writes composition/index.html (the HyperFrames composition) from composition/timeline.json and captions.mjs.
// Every time in the video is derived from the recorded marks, so re-recording and rebuilding re-times it all.
import fs from 'fs';
import path from 'path';
import { CAPTIONS, TEXT } from './captions.mjs';

const ROOT = path.resolve(import.meta.dirname, '..');
const clips = JSON.parse(fs.readFileSync(path.join(ROOT, 'composition/timeline.json'), 'utf8'));

const INTRO_SECONDS = 4;
const SLACK_INTRO_SECONDS = 3;
const OUTRO_SECONDS = 6.5;
const CAPTION_GAP = 0.08;

const round = (value) => +value.toFixed(2);
const webStart = INTRO_SECONDS;
const isolationStart = webStart + clips.web.duration;
const webWindowEnd = isolationStart + clips.isolation.duration;
const slackStart = webWindowEnd + SLACK_INTRO_SECONDS;
const slackEnd = slackStart + clips.slack.duration;
const total = round(slackEnd + OUTRO_SECONDS);
const clipStarts = { web: webStart, isolation: isolationStart, slack: slackStart };

function captionTimes(clip) {
  const { marks, duration } = clips[clip];
  const items = CAPTIONS[clip].filter(({ at }) => at in marks);
  return items.map((caption, index) => {
    const start = clipStarts[clip] + marks[caption.at];
    const next = items[index + 1];
    const end = next ? clipStarts[clip] + marks[next.at] - CAPTION_GAP : clipStarts[clip] + duration - 0.3;
    return { ...caption, start: round(start), end: round(end) };
  });
}

const captions = ['web', 'isolation', 'slack'].flatMap(captionTimes);
const captionHtml = captions
  .map(
    ({ title, sub, start, end }, index) =>
      `<div id="cap-${index}" class="clip cap" data-start="${start}" data-duration="${round(end - start)}" data-track-index="4">` +
      `<div class="cap-box"><div class="cap-main">${title}</div>${sub ? `<div class="cap-sub">${sub}</div>` : ''}</div></div>`,
  )
  .join('\n      ');

// The Slack recording is cropped to the conversation pane; scale it to fit the same window height as the web clip.
const VIEW_HEIGHT = 810;
const slackScale = VIEW_HEIGHT / clips.slack.crop.height;
const slackWidth = Math.round(clips.slack.crop.width * slackScale);

const html = `<!doctype html>
<html lang="en">
  <head>
    <meta charset="UTF-8" />
    <meta name="viewport" content="width=1920, height=1080" />
    <!-- Generated by scripts/compose.mjs. Edit scripts/captions.mjs or the generator, not this file. -->
    <script src="https://cdn.jsdelivr.net/npm/gsap@3.15.0/dist/gsap.min.js"></script>
    <style>
      :root { --brand: #b4532a; --brand-deep: #7a3418; --cream: #faf6f0; --ink: #2b211b; --muted: #6f625a; }
      * { margin: 0; padding: 0; box-sizing: border-box; }
      html, body { width: 1920px; height: 1080px; overflow: hidden; background: #2a1a12; }
      #root { position: relative; width: 1920px; height: 1080px; overflow: hidden; font-family: "Segoe UI", system-ui, sans-serif; }
      #bg { position: absolute; inset: 0; background:
        radial-gradient(1100px 700px at 10% 6%, rgba(232, 150, 100, 0.55), transparent 62%),
        radial-gradient(1000px 760px at 94% 98%, rgba(240, 205, 160, 0.6), transparent 60%),
        linear-gradient(135deg, #3b2216 0%, #7a3418 45%, #b4532a 75%, #e0b07f 100%); }

      .win { position: absolute; top: 30px; border-radius: 16px; overflow: hidden; opacity: 0; background: #fff;
        box-shadow: 0 0 0 1px rgba(255,255,255,0.25), 0 4px 10px rgba(20,8,2,0.2), 0 36px 80px -12px rgba(20,8,2,0.6); }
      .bar { height: 40px; background: linear-gradient(#f7f3ee, #ebe4dc); border-bottom: 1px solid rgba(60,30,10,0.12); position: relative; }
      .lights { position: absolute; left: 18px; top: 14px; display: flex; gap: 8px; }
      .lights i { width: 12px; height: 12px; border-radius: 50%; display: block; }
      .lights i:nth-child(1) { background: #ff5f57; } .lights i:nth-child(2) { background: #febc2e; } .lights i:nth-child(3) { background: #28c840; }
      .url { position: absolute; left: 50%; top: 7px; width: 520px; margin-left: -260px; height: 26px; border-radius: 8px; background: rgba(255,255,255,0.92);
        box-shadow: inset 0 0 0 1px rgba(60,30,10,0.12); color: #6b5b50; font: 500 14px/26px "Segoe UI", sans-serif; text-align: center; }
      .view { position: relative; overflow: hidden; }
      .view video { position: absolute; left: 0; top: 0; width: 100%; height: 100%; object-fit: fill; display: block; }
      #web-win { left: 240px; width: 1440px; }
      #web-win .view { width: 1440px; height: ${VIEW_HEIGHT}px; background: #fff; }
      #slack-win { left: ${Math.round((1920 - slackWidth) / 2)}px; width: ${slackWidth}px; }
      #slack-win .view { width: ${slackWidth}px; height: ${VIEW_HEIGHT}px; background: #1a1d21; }
      #slack-win .bar { background: linear-gradient(#3f0e40, #350d36); border-bottom-color: rgba(0,0,0,0.3); }
      #slack-win .url { background: rgba(255,255,255,0.12); color: #f2e9f2; box-shadow: none; }

      .cap { position: absolute; left: 0; top: 880px; width: 1920px; height: 200px; display: flex; align-items: center; justify-content: center; }
      .cap-box { max-width: 1600px; padding: 14px 44px 16px; border-radius: 20px; background: rgba(255,255,255,0.97); text-align: center;
        box-shadow: 0 18px 44px -10px rgba(20,8,2,0.55); border-bottom: 5px solid var(--brand); }
      .cap-main { color: var(--ink); font-size: 42px; font-weight: 700; line-height: 1.2; white-space: nowrap; }
      .cap-sub { color: var(--muted); font-size: 28px; font-weight: 500; line-height: 1.3; margin-top: 4px; }
      .cap-sub code, .card code { font-family: Consolas, monospace; font-size: 1em; color: var(--brand-deep); background: #f6ebe3; padding: 1px 8px; border-radius: 6px; }

      .full { position: absolute; inset: 0; display: flex; align-items: center; justify-content: center; }
      .card { width: 1240px; padding: 64px 80px 68px; border-radius: 32px; background: rgba(255,255,255,0.97); text-align: center;
        box-shadow: 0 40px 90px -16px rgba(20,8,2,0.6); }
      .card h1 { color: var(--ink); font-family: Georgia, serif; font-size: 104px; font-weight: 700; line-height: 1.05; }
      .card h2 { color: var(--ink); font-family: Georgia, serif; font-size: 76px; font-weight: 700; }
      .card .rule { width: 120px; height: 6px; border-radius: 3px; background: var(--brand); margin: 26px auto 30px; }
      .card p { color: var(--muted); font-size: 38px; font-weight: 500; line-height: 1.4; }
      .card .chips { display: flex; justify-content: center; gap: 18px; margin-top: 34px; }
      .card .chips span { font-size: 28px; font-weight: 600; color: var(--brand-deep); background: #f6ebe3; border-radius: 999px; padding: 8px 26px; }
      .card .link { margin-top: 14px; color: var(--brand); font-size: 44px; font-weight: 700; }
      .card .label { margin-top: 30px; color: var(--muted); font-size: 28px; font-weight: 600; text-transform: uppercase; letter-spacing: 0.08em; }
      .card .repo { margin-top: 8px; color: var(--ink); font-size: 34px; font-weight: 600; }
    </style>
  </head>
  <body>
    <div id="root" data-composition-id="main" data-start="0" data-duration="${total}" data-width="1920" data-height="1080">
      <div id="bg"></div>

      <div id="intro" class="clip full" data-start="0" data-duration="${INTRO_SECONDS}" data-track-index="1">
        <div class="card" id="intro-card">
          <h1>${TEXT.title}</h1>
          <div class="rule"></div>
          <p>${TEXT.tagline}</p>
          <div class="chips"><span>Web</span><span>Slack</span><span>Gemini + tools</span></div>
          <div class="label">by ${TEXT.author}</div>
        </div>
      </div>

      <div id="web-win" class="win">
        <div class="bar"><div class="lights"><i></i><i></i><i></i></div><div class="url" data-layout-ignore>${TEXT.webBar}</div></div>
        <div class="view">
          <video id="web-video" class="clip" src="${clips.web.file}" muted playsinline data-start="${webStart}" data-duration="${clips.web.duration}" data-track-index="0"></video>
          <video id="isolation-video" class="clip" src="${clips.isolation.file}" muted playsinline data-start="${round(isolationStart)}" data-duration="${clips.isolation.duration}" data-track-index="0"></video>
        </div>
      </div>

      <div id="slack-intro" class="clip full" data-start="${round(webWindowEnd)}" data-duration="${SLACK_INTRO_SECONDS}" data-track-index="1">
        <div class="card" id="slack-card">
          <h2>${TEXT.slackIntroTitle}</h2>
          <div class="rule"></div>
          <p>${TEXT.slackIntro}</p>
        </div>
      </div>

      <div id="slack-win" class="win">
        <div class="bar"><div class="lights"><i></i><i></i><i></i></div><div class="url" data-layout-ignore>${TEXT.slackBar}</div></div>
        <div class="view">
          <video id="slack-video" class="clip" src="${clips.slack.file}" muted playsinline data-start="${round(slackStart)}" data-duration="${clips.slack.duration}" data-track-index="2"></video>
        </div>
      </div>

      <div id="caps">
      ${captionHtml}
      </div>

      <div id="outro" class="clip full" data-start="${round(slackEnd)}" data-duration="${OUTRO_SECONDS}" data-track-index="1">
        <div class="card" id="outro-card">
          <h2>Try it live</h2>
          <div class="rule"></div>
          <div class="link">${TEXT.liveUrl}</div>
          <div class="label">Code, architecture and decisions</div>
          <div class="repo">${TEXT.repoUrl}</div>
        </div>
      </div>
    </div>
    <script>
      const CAPTIONS = ${JSON.stringify(captions.map(({ start, end }, i) => ({ i, start, end })))};
      const tl = gsap.timeline({ paused: true });

      const cardIn = (selector, at) => tl.fromTo(selector, { opacity: 0, y: 50, scale: 0.96 }, { opacity: 1, y: 0, scale: 1, duration: 0.7, ease: "power3.out" }, at);
      const cardOut = (selector, at) => tl.to(selector, { opacity: 0, y: -40, scale: 0.97, duration: 0.45, ease: "power2.in" }, at);
      const winIn = (selector, at) => tl.fromTo(selector, { opacity: 0, y: 70, scale: 0.94 }, { opacity: 1, y: 0, scale: 1, duration: 0.8, ease: "power3.out" }, at);
      const winOut = (selector, at) => tl.to(selector, { opacity: 0, y: -50, scale: 0.95, duration: 0.5, ease: "power2.in" }, at);

            tl.fromTo("#intro-card .chips span", { opacity: 0, y: 16 }, { opacity: 1, y: 0, duration: 0.4, stagger: 0.15 }, 0.8);
      cardOut("#intro-card", ${INTRO_SECONDS - 0.5});

      winIn("#web-win", ${webStart - 0.4});
      winOut("#web-win", ${round(webWindowEnd - 0.5)});
      cardIn("#slack-card", ${round(webWindowEnd + 0.1)});
      cardOut("#slack-card", ${round(slackStart - 0.55)});
      winIn("#slack-win", ${round(slackStart - 0.4)});
      winOut("#slack-win", ${round(slackEnd - 0.5)});
      cardIn("#outro-card", ${round(slackEnd)});

      CAPTIONS.forEach(({ i, start, end }) => {
        const box = "#cap-" + i + " .cap-box";
        tl.fromTo(box, { opacity: 0, y: 22 }, { opacity: 1, y: 0, duration: 0.35, ease: "power2.out" }, start);
        tl.to(box, { opacity: 0, y: -10, duration: 0.25, ease: "power1.in" }, end - 0.27);
      });

      window.__timelines = window.__timelines || {};
      window.__timelines["main"] = tl;
      tl.seek(0);
    </script>
  </body>
</html>
`;

fs.writeFileSync(path.join(ROOT, 'composition/index.html'), html);
console.log(`Wrote composition/index.html (${total}s, ${captions.length} captions)`);
